const { runBrowser } = require('./browser.cjs');

runBrowser(async () => {
  const p=probe, q=id=>document.getElementById(id);
  p.newGame();
  p.S.stage=3; p.S.score=12000; p.openIntro();
  await p.beginStage();
  p.S.score+=2300; p.S.time=31.4;
  q('btnPause').click();
  check(p.S.paused && q('pause').classList.contains('show'), '일시정지 팝업 없음');
  check(q('pauseStage').textContent.includes('STAGE 4'), '현재 스테이지 오류');
  check(q('pauseTime').textContent==='32초', '남은 시간 오류');
  check(q('pauseScore').textContent===(2300).toLocaleString(), '총점 대신 스테이지 점수를 표시해야 한다');
  check(q('pauseTarget').textContent===p.STAGES[3].target.toLocaleString(), '목표 점수 오류');
  const time=p.S.time;
  await delay(200);
  check(p.S.time===time, '일시정지 중 시간 경과');
  check(document.activeElement===q('btnResume'), '계속하기에 초점 없음');
  p.S.lives=1; p.startFever(); p.spawn('fish',0);
  q('btnRestart').click();
  check(!q('pauseConfirm').hidden && p.S.paused, '재시작 확인 창 없음');
  q('btnPauseCancel').click();
  check(p.S.lives===1 && p.S.score===14300 && p.S.time===time, '취소가 게임 상태를 변경함');
  q('btnRestart').click();
  window.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape'}));
  check(q('pauseConfirm').hidden && p.S.paused, 'Esc가 확인 창만 닫아야 함');
  q('btnRestart').click(); q('btnPauseConfirm').click();
  check(q('intro').classList.contains('show') && !p.S.running, '재시작 후 스테이지 안내가 아님');
  check(p.S.stage===3 && p.S.score===12000 && p.S.stageStart===12000, '재시작 시 이전 스테이지 총점 손실');
  check(p.S.lives===3 && p.S.time===60 && !p.S.feverOn && p.S.fever===0 && p.S.items.length===0, '재시작 상태 초기화 오류');
  await p.beginStage(); q('btnPause').click(); q('btnQuit').click();
  check(!q('pauseConfirm').hidden && p.S.running, '타이틀 이동 전 확인이 없음');
  q('btnPauseCancel').click();
  check(p.S.paused && document.activeElement===q('btnQuit'), '타이틀 이동 취소 시 일시정지 유지 오류');
  q('btnQuit').click(); q('btnPauseConfirm').click();
  check(!p.S.running && q('title').classList.contains('show'), '확인 후 타이틀 이동 실패');
});
console.log('PASS: 일시정지 팝업의 스테이지 정보와 시간 정지');
